"""End-to-end pipeline.

python run_pipeline.py --data data/911.csv
python run_pipeline.py --data data/911.csv --skip-forecast --skip-geo   # faster iteration
"""

import argparse
import json
import logging
import platform
import time
from datetime import datetime, timezone

import numpy as np
import pandas as pd
import sklearn

from src import anomalies, data, eda, forecast, geo, quality, staffing, stats_tests
from src.config import DATA_RAW, REPORTS, SEED
from src.eda import DOW

log = logging.getLogger("pipeline")


def write_findings(df, wk, chi, holdout, interval, ablation, daily, staff, hotspots, stability):
    ems = df[df["category"] == "EMS"]
    naive, gbm = holdout.iloc[0], holdout.iloc[1]
    ems_staff = staff[staff["category"] == "EMS"]
    peak = ems_staff.loc[ems_staff["units_needed"].idxmax()]
    mix = ", ".join(f"{k} {v:.1f}%" for k, v in (df["category"].value_counts(normalize=True) * 100).items())
    lines = [
        "# Key findings (auto-generated by run_pipeline.py)\n",
        f"- {len(df):,} calls analysed from {df['timeStamp'].min():%Y-%m-%d} to {df['timeStamp'].max():%Y-%m-%d}.",
        f"- Category split: {mix}.",
        f"- Busiest hour overall: {df['hour'].value_counts().idxmax()}:00. "
        f"Busiest weekday: {DOW[df['dow_num'].value_counts().idxmax()]}.",
        f"- {ems['hour'].between(10, 17).mean() * 100:.1f}% of EMS calls fall between 10:00 and 17:59.",
        f"- Weekdays average {wk['weekday_mean']:.0f} calls/day vs {wk['weekend_mean']:.0f} on weekends "
        f"({wk['pct_difference']:+.1f}%, Mann-Whitney p={wk['p_value']:.3g}, rank-biserial={wk['rank_biserial']:.2f}).",
        f"- Category mix differs across the top townships: Cramer's V = {chi['cramers_v']:.3f}.",
    ]
    if hotspots is not None:
        top = hotspots.iloc[0]["top_township"] if len(hotspots) else "n/a"
        lines.append(f"- {len(hotspots)} EMS hotspot clusters found with DBSCAN; the largest is around {top}.")
    if stability is not None and len(stability) and stability["pct_a_persisting_in_b"].notna().any():
        lines.append(
            f"- Hotspot stability: on average {stability['pct_a_persisting_in_b'].mean():.0f}% of one year's "
            "hotspots reappear within 1 km the next year."
        )
    if holdout is not None:
        lines.append(
            f"- 24h-ahead hourly forecast: model MAE {gbm['MAE']:.2f} vs seasonal-naive {naive['MAE']:.2f} "
            f"({(1 - gbm['MAE'] / naive['MAE']) * 100:.1f}% lower error)."
        )
        lines.append(
            f"- 80% prediction interval achieved {interval['empirical_coverage_pct']:.1f}% empirical coverage."
        )
        a = ablation.set_index("model")["MAE"]
        lines.append(
            f"- Ablation: calendar-only MAE {a.iloc[0]:.2f} -> with lags {a.iloc[1]:.2f} -> "
            f"with holiday flag {a.iloc[2]:.2f}."
        )
    lines.append(f"- {int(daily['anomaly'].sum())} anomalous days flagged out of {len(daily):,} (robust z > 3.5).")
    lines.append(
        f"- Recommended EMS units range from {ems_staff['units_needed'].min()} (quietest hour) to "
        f"{int(peak['units_needed'])} (peak: {DOW[int(peak['dow_num'])]} at {int(peak['hour'])}:00)."
    )
    (REPORTS / "key_findings.md").write_text("\n".join(lines))
    log.info("\n%s", "\n".join(lines))


def main(path, skip_geo=False, skip_forecast=False):
    t0 = time.time()
    REPORTS.mkdir(exist_ok=True)

    log.info("[1/8] Loading, auditing and cleaning")
    raw = data.load_raw(path)
    df = data.clean(raw)
    quality.save_quality(quality.quality_report(raw, df))
    data.save_processed(df)

    log.info("[2/8] EDA plots")
    eda.run_all(df)

    log.info("[3/8] Statistical tests")
    wk = stats_tests.weekday_vs_weekend(df)
    chi = stats_tests.category_mix_by_township(df)
    (REPORTS / "stats_results.json").write_text(json.dumps({"weekday_vs_weekend": wk, "township_mix": chi}, indent=2))

    hotspots = stability = None
    if skip_geo:
        log.info("[4/8] Geospatial analysis (skipped)")
    else:
        log.info("[4/8] Geospatial analysis")
        hotspots = geo.find_hotspots(df)
        hotspots.to_csv(REPORTS / "ems_hotspots.csv", index=False)
        curve, centers_by_k = geo.station_coverage_curve(df)
        curve.to_csv(REPORTS / "station_coverage_curve.csv", index=False)
        geo.build_map(df, hotspots, centers=centers_by_k[6])
        stability = geo.hotspot_stability(df)
        stability.to_csv(REPORTS / "hotspot_stability.csv", index=False)

    holdout = interval = ablation = None
    if skip_forecast:
        log.info("[5/8] Forecasting (skipped)")
    else:
        log.info("[5/8] Forecasting")
        holdout, cv, interval = forecast.evaluate(df)
        holdout.to_csv(REPORTS / "forecast_holdout_metrics.csv")
        cv.to_csv(REPORTS / "forecast_cv_metrics.csv", index=False)
        (REPORTS / "forecast_interval.json").write_text(json.dumps(interval, indent=2))
        ablation = pd.read_csv(REPORTS / "forecast_ablation.csv")
        log.info("\n%s\n%s", holdout.round(3), cv.round(3))

    log.info("[6/8] Anomaly detection")
    daily = anomalies.detect_daily_anomalies(df)
    anomalies.save_anomalies(daily)

    log.info("[7/8] Staffing recommendation")
    staff = staffing.staffing_table(df)
    for cat in df["category"].unique():
        staffing.plot_staffing_heatmap(staff, cat)

    log.info("[8/8] Writing report")
    write_findings(df, wk, chi, holdout, interval, ablation, daily, staff, hotspots, stability)
    (REPORTS / "run_metadata.json").write_text(
        json.dumps(
            {
                "run_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "input_file": str(path),
                "rows_analysed": int(len(df)),
                "seed": SEED,
                "python": platform.python_version(),
                "pandas": pd.__version__,
                "numpy": np.__version__,
                "scikit_learn": sklearn.__version__,
                "runtime_seconds": round(time.time() - t0, 1),
            },
            indent=2,
        )
    )
    log.info("Done in %.1fs. Outputs in %s", time.time() - t0, REPORTS)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=str(DATA_RAW), help="path to 911.csv")
    ap.add_argument("--skip-geo", action="store_true")
    ap.add_argument("--skip-forecast", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-7s %(message)s", datefmt="%H:%M:%S")
    main(args.data, args.skip_geo, args.skip_forecast)
